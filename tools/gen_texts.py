import re
reps = []
def walk(x):
    if isinstance(x, dict):
        if set(x.keys()) >= {"s", "e", "t"}:
            reps.append(x)
        else:
            for v in x.values(): walk(v)
    elif isinstance(x, list):
        for v in x: walk(v)
